/*
Function: TestGenerateWilson
Purpose: Checks connectivity and passage counts for several

	maze dimensions and random seeds.

Precondition: Maze and Wilson functions are implemented.
Postcondition: Test failures are reported if found.
Parameters: t (in/out) - Go test context.
Returns: None.
*/
func TestGenerateWilson(t *testing.T) {
	sizes := [][2]int{
		{1, 1}, {1, 5}, {5, 1}, {2, 2},
		{3, 5}, {5, 5}, {10, 10}, {20, 20},
	} // Row and column combinations.

	for _, size := range sizes { // Current dimensions.
		for seed := int64(1); seed <= 5; seed++ { // Fixed test seed.
			maze := NewMaze(size[0], size[1])        // Test maze.
			random := rand.New(rand.NewSource(seed)) // Random source.

			GenerateWilson(maze, random)

			expected := size[0] * size[1]     // Required cell count.
			passages := countPassages(maze)   // Actual passage count.
			reachable := countReachable(maze) // Connected cell count.

			if passages != expected-1 {
				t.Errorf("%dx%d, seed %d: expected %d passages, got %d",
					size[0], size[1], seed, expected-1, passages)
			}

			if reachable != expected {
				t.Errorf("%dx%d, seed %d: expected %d reachable cells, got %d",
					size[0], size[1], seed, expected, reachable)
			}
		}
	}
}

/*
Function: countPassages
Purpose: Counts connections between neighboring cells.
Precondition: m is an initialized maze with consistent walls.
Postcondition: The maze is unchanged.
Parameters: m (in) - maze being inspected.
Returns: Number of open connections between cells.
*/
func countPassages(m *Maze) int {
	count := 0 // Number of open connections.

	for r := 0; r < m.Rows(); r++ { // Current row.
		for c := 0; c < m.Cols(); c++ { // Current column.
			cell := NewCell(r, c) // Cell being inspected.

			// Count only east and south passages to avoid
			// counting the same connection twice.
			if c < m.Cols()-1 && !m.HasWall(cell, east) {
				count++
			}

			if r < m.Rows()-1 && !m.HasWall(cell, south) {
				count++
			}
		}
	}

	return count
}

/*
Function: countReachable
Purpose: Counts cells reachable through open passages using BFS.
Precondition: m is an initialized maze with positive dimensions.
Postcondition: The maze is unchanged.
Parameters: m (in) - maze being inspected.
Returns: Number of cells reachable from cell (0,0).
*/
func countReachable(m *Maze) int {
	start := NewCell(0, 0)      // BFS starting location.
	queue := []Cell{start}      // Cells waiting to be explored.
	seen := make(map[Cell]bool) // Cells discovered by BFS.

	seen[start] = true

	directions := [4][2]int{
		{-1, 0}, {0, 1}, {1, 0}, {0, -1},
	} // Coordinate changes in north, east, south, west order.

	for len(queue) > 0 {
		current := queue[0] // Next cell to explore.
		queue = queue[1:]

		for d, change := range directions { // Direction and offset.
			if !m.HasWall(current, d) {
				nextRow := current.Row() + change[0] // Neighbor row.
				nextCol := current.Col() + change[1] // Neighbor column.

				// Ignore positions outside the grid.
				if nextRow >= 0 && nextRow < m.Rows() &&
					nextCol >= 0 && nextCol < m.Cols() {

					next := NewCell(nextRow, nextCol) // Neighbor.

					if !seen[next] {
						seen[next] = true
						queue = append(queue, next)
					}
				}
			}
		}
	}

	return len(seen)
}

/*
Function: TestRandomWalk
Purpose: Verifies that random walks contain unique cells and

	terminate upon reaching the existing maze.

Precondition: randomWalk is implemented.
Postcondition: Test failures are reported if found.
Parameters: t (in/out) - Go test context.
Returns: None.
*/
func TestRandomWalk(t *testing.T) {
	maze := NewMaze(5, 5)  // Test maze.
	root := NewCell(4, 4)  // Existing maze location.
	start := NewCell(0, 0) // Starting location.

	visited := map[Cell]bool{root: true} // Permanent maze.

	for seed := int64(1); seed <= 20; seed++ { // Test seed.
		random := rand.New(rand.NewSource(seed))         // Random source.
		path := randomWalk(maze, start, visited, random) // Test walk.
		seen := make(map[Cell]bool)                      // Cells encountered in the path.

		if path[0] != start || path[len(path)-1] != root {
			t.Fatal("Random walk has incorrect endpoints")
		}

		for _, cell := range path { // Current path cell.
			if seen[cell] {
				t.Fatal("Random walk contains a loop")
			}

			seen[cell] = true
		}

		if len(visited) != 1 {
			t.Fatal("Random walk modified the permanent maze")
		}

		if countPassages(maze) != 0 {
			t.Fatal("Random walk removed walls prematurely")
		}
	}
}
